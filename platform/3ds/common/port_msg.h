#ifndef AC3DS_PORT_MSG_H
#define AC3DS_PORT_MSG_H

#define PORT_MSG_FIRST    0x3F91
#define PORT_MSG_COUNT    0x40
#define PORT_STRING_FIRST 607

#define PORT_MSG_ORDINANCE_FIRST PORT_MSG_FIRST
#define PORT_MSG_ORDINANCE_COUNT 28
#define PORT_MSG_LOOK_FIRST      (PORT_MSG_ORDINANCE_FIRST + PORT_MSG_ORDINANCE_COUNT)
#define PORT_MSG_LOOK_COUNT      24
#define PORT_MSG_RESUME          (PORT_MSG_LOOK_FIRST + PORT_MSG_LOOK_COUNT)
#define PORT_MSG_END             (PORT_MSG_RESUME + 1)

#define PORT_STRING_ORDINANCE_FIRST PORT_STRING_FIRST
#define PORT_STRING_ORDINANCE_COUNT 6
#define PORT_STRING_LOOK_FIRST      (PORT_STRING_ORDINANCE_FIRST + PORT_STRING_ORDINANCE_COUNT)
#define PORT_STRING_LOOK_COUNT      22

_Static_assert(PORT_MSG_END <= PORT_MSG_FIRST + PORT_MSG_COUNT, "room for the port's messages");

#endif /* AC3DS_PORT_MSG_H */
